// Package chrony renders the group time-service policy from Net peers.
package chrony

import (
	"bytes"
	"context"
	"fmt"
	"net"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
	"unicode"

	"github.com/outpostos/OutpostNet/pkg/tunnel/tlsutil"
)

// Peer uses the Net management API's node_id/addr representation. Addr is
// the tunnel endpoint; chrony uses its host with standard NTP/NTS ports.
type Peer struct {
	NodeID string `json:"node_id"`
	Addr   string `json:"addr"`
}

// GNSS is opt-in; Parameter is a gpsd SHM unit or SOCK path. PPS is optional.
type GNSS struct{ Driver, Parameter, PPS string }

// Config identifies the local node and its group credentials. NTPPort and
// NTSKEPort select the group-wide listen and per-source ports; zero keeps the
// standard NTP 123 and NTS-KE 4460.
type Config struct {
	NodeID, CAFile, CertFile, KeyFile string
	GNSS                              GNSS
	NTPPort, NTSKEPort                int
}

const defaultNTPPort, defaultNTSKEPort = 123, 4460

// Lookup resolves DNS peers to exact access rules. Nil uses the system resolver.
type Lookup func(context.Context, string) ([]net.IP, error)

// Render returns a deterministic fragment without changing files or the clock.
// DNS is resolved on each render; unresolved peers fail closed.
func Render(ctx context.Context, cfg Config, peers []Peer, lookup Lookup) ([]byte, error) {
	if cfg.NodeID == "" {
		return nil, fmt.Errorf("node_id is required")
	}
	for _, path := range []string{cfg.CAFile, cfg.CertFile, cfg.KeyFile} {
		if !safePath(path) {
			return nil, fmt.Errorf("credential paths must be absolute without whitespace or config metacharacters")
		}
	}
	if lookup == nil {
		lookup = func(ctx context.Context, host string) ([]net.IP, error) {
			return net.DefaultResolver.LookupIP(ctx, "ip", host)
		}
	}
	ntpPort, ntskePort := cfg.NTPPort, cfg.NTSKEPort
	if ntpPort == 0 {
		ntpPort = defaultNTPPort
	}
	if ntskePort == 0 {
		ntskePort = defaultNTSKEPort
	}
	for _, p := range []struct {
		name string
		port int
	}{{"NTP", ntpPort}, {"NTS-KE", ntskePort}} {
		if p.port < 1 || p.port > 65535 {
			return nil, fmt.Errorf("invalid %s port", p.name)
		}
	}
	nonDefaultNTP := ntpPort != defaultNTPPort
	nonDefaultNTSKE := ntskePort != defaultNTSKEPort
	var srcPorts string
	if nonDefaultNTP {
		srcPorts += " port " + strconv.Itoa(ntpPort)
	}
	if nonDefaultNTSKE {
		srcPorts += " ntsport " + strconv.Itoa(ntskePort)
	}
	var b bytes.Buffer
	fmt.Fprintln(&b, "# Generated by outpostnet-agent chrony (ADR-0006 D7).")
	fmt.Fprintln(&b, "local stratum 10 orphan\nmakestep 1.0 1\nnocerttimecheck 1\nnosystemcert")
	if nonDefaultNTP {
		fmt.Fprintf(&b, "port %d\n", ntpPort)
	}
	if nonDefaultNTSKE {
		fmt.Fprintf(&b, "ntsport %d\n", ntskePort)
	}
	fmt.Fprintf(&b, "ntstrustedcerts 1 %s\nntsservercert %s\nntsserverkey %s\nauthselectmode require\ndeny all\n", cfg.CAFile, cfg.CertFile, cfg.KeyFile)
	peers = append([]Peer(nil), peers...)
	sort.Slice(peers, func(i, j int) bool { return peers[i].NodeID < peers[j].NodeID })
	seen := map[string]bool{}
	hosts := map[string]bool{}
	access := map[string]bool{}
	for _, p := range peers {
		if p.NodeID == "" || seen[p.NodeID] {
			return nil, fmt.Errorf("peer node_id must be nonempty and unique")
		}
		seen[p.NodeID] = true
		if p.NodeID == cfg.NodeID {
			continue
		}
		host, port, err := net.SplitHostPort(p.Addr)
		if err != nil {
			return nil, fmt.Errorf("peer addr must be host:port")
		}
		n, err := strconv.Atoi(port)
		if err != nil || n < 1 || n > 65535 {
			return nil, fmt.Errorf("invalid peer port")
		}
		ip := net.ParseIP(host)
		var ips []net.IP
		if ip != nil {
			host = ip.String()
			ips = []net.IP{ip}
		} else {
			if !tlsutil.ValidDNSName(host) {
				return nil, fmt.Errorf("invalid peer host")
			}
			ips, err = lookup(ctx, host)
			if err != nil {
				return nil, fmt.Errorf("resolve peer %s: %w", p.NodeID, err)
			}
		}
		if len(ips) == 0 {
			return nil, fmt.Errorf("peer has no IP addresses")
		}
		for _, ip := range ips {
			if ip.To16() == nil || ip.IsUnspecified() || ip.IsMulticast() {
				return nil, fmt.Errorf("peer must have unicast IP addresses")
			}
			access[ip.String()] = true
		}
		if hosts[host] {
			return nil, fmt.Errorf("duplicate peer host")
		}
		hosts[host] = true
		fmt.Fprintf(&b, "server %s%s iburst nts certset 1\n", host, srcPorts)
	}
	addresses := make([]string, 0, len(access))
	for ip := range access {
		addresses = append(addresses, ip)
	}
	sort.Strings(addresses)
	for _, ip := range addresses {
		fmt.Fprintf(&b, "allow %s\n", ip)
	}
	g := cfg.GNSS
	switch g.Driver {
	case "":
		if g.Parameter != "" || g.PPS != "" {
			return nil, fmt.Errorf("GNSS receiver required for PPS")
		}
	case "SHM":
		n, err := strconv.Atoi(g.Parameter)
		if err != nil || n < 0 || n > 255 {
			return nil, fmt.Errorf("invalid gpsd SHM unit")
		}
	case "SOCK":
		if !safePath(g.Parameter) {
			return nil, fmt.Errorf("invalid gpsd SOCK path")
		}
	default:
		return nil, fmt.Errorf("GNSS driver must be SHM or SOCK")
	}
	if g.Driver != "" {
		fmt.Fprintf(&b, "refclock %s %s refid GNSS prefer\n", g.Driver, g.Parameter)
		if g.PPS != "" {
			if !safePath(g.PPS) {
				return nil, fmt.Errorf("invalid PPS path")
			}
			fmt.Fprintf(&b, "refclock PPS %s refid PPS lock GNSS prefer\n", g.PPS)
		}
	}
	return b.Bytes(), nil
}

func safePath(path string) bool {
	return filepath.IsAbs(path) && !strings.ContainsAny(path, "#;!%\\\"':") && !strings.ContainsFunc(path, func(r rune) bool { return unicode.IsSpace(r) || unicode.IsControl(r) })
}
